export interface IconProps {
  /** Kebab-case lucide name, e.g. "graduation-cap". */
  name: string;
  /** Edge length in px. */
  size?: number;
  /** Any CSS colour; defaults to `currentColor`. */
  color?: string;
  strokeWidth?: number;
  className?: string;
}

/**
 * `<Icon name="graduation-cap" size={18} />`
 *
 * Everything is sized in px because the comp sizes icons in px; colour is left
 * to `currentColor` unless a caller needs a tint that is not the text colour.
 */
export function Icon({ name, size = 18, color, strokeWidth = 2, className }: IconProps) {
  const Cmp = ICONS[name] ?? Circle;
  return (
    <Cmp
      size={size}
      color={color}
      strokeWidth={strokeWidth}
      className={className}
      aria-hidden="true"
      focusable="false"
    />
  );
}

export default Icon;
