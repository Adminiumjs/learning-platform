/*
 * Icon — the kebab-case lucide registry.
 *
 * The comp authors icon names as kebab-case strings in its data ("graduation-cap",
 * "circle-dot", …), and the ported screens keep those strings so a record can
 * still say which icon it wants. This registry maps every name the comp uses —
 * all 121 of them, extracted from the comp and checked against the package —
 * to its `lucide-react` component.
 *
 * Imports are explicit so the bundle only carries the icons the app actually
 * uses; `lucide-react` ships well over a thousand. An unknown name renders
 * `Circle` rather than throwing, so a typo degrades instead of blanking a
 * screen. Need one that is not here? Add the import and one registry line.
 */

